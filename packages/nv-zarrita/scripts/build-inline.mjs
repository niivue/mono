// Build dist/inline (the `zarrita-wasm/inline` entry) from dist/:
// same modules, but the wasm module is embedded as base64, there is no worker
// pool and no numcodecs fallback. Run after tsc has written dist/.
import {
  cpSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { join } from 'node:path'

const dist = new URL('../dist/', import.meta.url).pathname
const out = join(dist, 'inline')
const src = new URL('../src/', import.meta.url).pathname

rmSync(out, { recursive: true, force: true })
for (const name of readdirSync(dist)) {
  if (name === 'inline') continue
  cpSync(join(dist, name), join(out, name), { recursive: true })
}
for (const f of ['wasm/zarrita.wasm', 'wasm/worker.js']) rmSync(join(out, f))
cpSync(join(src, 'wasm/assets.inline.js'), join(out, 'wasm/assets.js'))
cpSync(
  new URL('./fallback.inline.js', import.meta.url).pathname,
  join(out, 'codecs/fallback.js'),
)
rmSync(join(out, 'codecs/fallback.js.map'), { force: true })

const b64 = readFileSync(join(dist, 'wasm/zarrita.wasm')).toString('base64')
writeFileSync(
  join(out, 'wasm/zarrita.wasm.js'),
  `// Generated by scripts/build-inline.mjs: zarrita.wasm as base64.
const b64 = "${b64}";
export function wasmBytes() {
	if (typeof Uint8Array.fromBase64 === "function") return Uint8Array.fromBase64(b64);
	const s = atob(b64);
	const bytes = new Uint8Array(s.length);
	for (let i = 0; i < s.length; i++) bytes[i] = s.charCodeAt(i);
	return bytes;
}
`,
)

// Guard the promises this entry makes.
const problems = []
const walk = (d) => {
  for (const n of readdirSync(d)) {
    const p = join(d, n)
    if (statSync(p).isDirectory()) walk(p)
    else if (p.endsWith('.js')) {
      const t = readFileSync(p, 'utf8')
      if (t.includes('import.meta')) problems.push(`${p}: import.meta`)
      if (/from\s*["']numcodecs|import\(\s*["']numcodecs/.test(t))
        problems.push(`${p}: imports numcodecs`)
    }
  }
}
walk(out)
if (problems.length) {
  console.error(`build-inline: ${problems.join('\n')}`)
  process.exit(1)
}
console.log(
  `build-inline: dist/inline ok (wasm ${(b64.length / 1024).toFixed(0)} KiB as base64)`,
)
