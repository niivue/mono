// OHIF's segmentation panel lists cornerstone's segmentation state for the
// active viewport id. A NiiVue pane's SEG drawing is entered there as a
// segmentation without voxel data (NiiVue keeps rendering its own drawing) and
// panel edits are mirrored back into the drawing. cornerstone refuses a
// representation on a viewport outside its rendering engine, so it is written
// into the state directly; everything the panel then calls is keyed by id only.

const LABELMAP = 'Labelmap'

type Color = number[]
type Rep = {
  visible?: boolean
  segments?: Record<number, { visible?: boolean }>
}
type Segment = {
  label?: string
  active?: boolean
  locked?: boolean
  cachedStats?: Record<string, unknown>
}
type Style = {
  renderFill?: boolean
  renderOutline?: boolean
  fillAlpha?: number
  outlineOpacity?: number
  outlineWidth?: number
  renderFillInactive?: boolean
  renderOutlineInactive?: boolean
  fillAlphaInactive?: number
  outlineOpacityInactive?: number
  outlineWidthInactive?: number
  fillAlphaAutoGenerated?: number
  outlineWidthAutoGenerated?: number
}
type Specifier = { segmentationId: string; type: string }
export interface CstSegmentation {
  addSegmentations(input: unknown[]): void
  removeSegmentationRepresentations(viewportId: string, s: object): void
  state: {
    removeColorLUT(index: number): void
    getColorLUT(index: number): unknown
    getSegmentation(
      id: string,
    ): { segments: Record<string, Segment> } | undefined
    getSegmentationRepresentation(
      viewportId: string,
      s: Specifier,
    ): Rep | undefined
  }
  config: {
    color: {
      addColorLUT(lut: Color[], index?: number): number
      getSegmentIndexColor(
        viewportId: string,
        id: string,
        i: number,
      ): Color | null
    }
    style: { getStyle(s: Specifier & { viewportId: string }): Style }
  }
  defaultSegmentationStateManager: {
    updateState(
      fn: (state: {
        viewportSegRepresentations: Record<string, unknown[]>
      }) => void,
    ): void
    addDefaultSegmentationRepresentation(
      state: unknown,
      viewportId: string,
      id: string,
      type: string,
      config: { colorLUTIndex: number },
    ): void
  }
  segmentationStyle: {
    setRenderInactiveSegmentations(viewportId: string, v: boolean): void
    getRenderInactiveSegmentations?(viewportId: string): boolean
  }
  triggerSegmentationEvents: {
    triggerSegmentationModified(id: string): void
    triggerSegmentationRepresentationModified(
      viewportId: string,
      id: string,
      type: string,
    ): void
  }
}

/**
 * Whether a pane draws `segmentationId` with its active style, its inactive
 * one, or not at all (cornerstone's renderInactiveSegmentations off).
 */
export function segmentationRole(
  service: OhifSegmentationService,
  cst: Pick<CstSegmentation, 'segmentationStyle'>,
  viewportId: string,
  segmentationId: string,
): 'active' | 'inactive' | 'hidden' {
  const active = service.getActiveSegmentation?.(viewportId)?.segmentationId
  if (!active || active === segmentationId) return 'active'
  return cst.segmentationStyle.getRenderInactiveSegmentations?.(viewportId) ===
    false
    ? 'hidden'
    : 'inactive'
}

// As NiiVue's drawing demo: a translucent fill under an opaque rim.
export const SEG_FILL_OPACITY = 0.5
export const SEG_RIM_OPACITY = 1

export type SegmentStats = { count: number; centroid: [number, number, number] }

export interface PanelSegment {
  value: number
  label: string
  rgb: [number, number, number]
}

/** Per-label voxel count and RAS-voxel centroid of a drawing bitmap, one pass. */
export function labelStats(bitmap: Uint8Array, dims: ArrayLike<number>) {
  const [nx = 0, ny = 0, nz = 0] = Array.from(dims)
  const n = new Float64Array(256)
  const sx = new Float64Array(256)
  const sy = new Float64Array(256)
  const sz = new Float64Array(256)
  let i = 0
  for (let z = 0; z < nz; z++)
    for (let y = 0; y < ny; y++)
      for (let x = 0; x < nx; x++, i++) {
        const v = bitmap[i] as number
        if (v === 0) continue
        n[v] = (n[v] as number) + 1
        sx[v] = (sx[v] as number) + x
        sy[v] = (sy[v] as number) + y
        sz[v] = (sz[v] as number) + z
      }
  const stats = new Map<number, SegmentStats>()
  for (let v = 1; v < 256; v++) {
    const count = n[v] as number
    if (count)
      stats.set(v, {
        count,
        centroid: [
          (sx[v] as number) / count,
          (sy[v] as number) / count,
          (sz[v] as number) / count,
        ],
      })
  }
  return stats
}

/**
 * NiiVue drawing opacities and rim width for a cornerstone labelmap style, its
 * *Inactive half while another segmentation (a contour one) is active on the
 * pane. The shader draws a rim only where the fill alpha is nonzero, so
 * outline-only keeps a 1/255 fill.
 */
export function drawOpacities(
  style: Style,
  isActive = true,
): {
  fill: number
  rim: number
  width: number
  outlineOnly: boolean
} {
  const renderFill = isActive
    ? style.renderFill
    : (style.renderFillInactive ?? style.renderFill)
  const renderOutline = isActive
    ? style.renderOutline
    : (style.renderOutlineInactive ?? style.renderOutline)
  const fillAlpha = isActive ? style.fillAlpha : style.fillAlphaInactive
  const outlineOpacity = isActive
    ? style.outlineOpacity
    : style.outlineOpacityInactive
  const fill = renderFill === false ? 0 : (fillAlpha ?? 0.5)
  const rim = renderOutline === false ? -1 : (outlineOpacity ?? 1)
  const outlineOnly = rim > 0 && fill === 0
  return {
    fill: outlineOnly ? 1 / 255 : fill,
    rim,
    width: (isActive ? style.outlineWidth : style.outlineWidthInactive) ?? 1,
    outlineOnly,
  }
}

/** Label colormap of the panel's segments; a hidden one gets alpha 0. */
export function panelColormap(
  rows: ReadonlyArray<{
    value: number
    label: string
    color: Color
    visible: boolean
  }>,
) {
  const cmap = { R: [0], G: [0], B: [0], A: [0], I: [0], labels: [''] }
  for (const r of rows) {
    cmap.R.push(r.color[0] ?? 0)
    cmap.G.push(r.color[1] ?? 0)
    cmap.B.push(r.color[2] ?? 0)
    cmap.A.push(r.visible ? (r.color[3] ?? 255) : 0)
    cmap.I.push(r.value)
    cmap.labels.push(r.label)
  }
  return cmap
}

/** A segment's panel statistics (cornerstone's cachedStats) from its voxel count. */
export function segmentStats(count: number, voxelMM3: number) {
  const volume = count * voxelMM3
  // No `center`: OHIF's own jump would then look for a cornerstone viewport.
  // The panel's statistics card lists namedStats (labels as OHIF's readableText).
  return {
    count,
    volume,
    namedStats: {
      count: { name: 'count', label: 'Voxel Count', value: count, order: 0 },
      volume: {
        name: 'volume',
        label: 'Volume',
        value: volume,
        unit: 'mm³',
        order: 1,
      },
    },
  }
}

export function cornerstoneSegmentation(
  extensionManager: OhifExtensionManager | undefined,
): CstSegmentation | undefined {
  return cornerstoneLibraries<{
    cornerstoneTools?: { segmentation?: CstSegmentation }
  }>(extensionManager)?.cornerstoneTools?.segmentation
}

/** A distinct colour for segment `i` (golden-angle hues), for segments the source did not colour. */
export function paletteColor(i: number): Color {
  const h = ((i * 137.508) % 360) / 60
  const x = Math.round(255 * (1 - Math.abs((h % 2) - 1)))
  const rgb = [
    [255, x, 0],
    [x, 255, 0],
    [0, 255, x],
    [0, x, 255],
    [x, 0, 255],
    [255, 0, x],
  ][Math.floor(h) % 6] as Color
  return [...rgb, 255]
}

/** What a pane shows in the panel, for its commands (save, jump). */
export interface NiivueSegmentationPane {
  viewportId: string
  segmentationId: string
  nv: Pick<NiiVue, 'drawingVolume'>
  /** The SEG or RTSTRUCT display set shown; synthetic for a new segmentation. */
  seg: OhifDisplaySet
  rt?: RtLabels
  /** The panel's rows: value, label, colour, voxel count and volume. */
  rows(): Array<{
    value: number
    label: string
    rgb: [number, number, number]
    count: number
    volume: number
    locked: boolean
    active: boolean
    visible: boolean
  }>
  jump(index: number): void
  /** The panel's Delete Segment: one undo step, voxels included. */
  deleteSegment(index: number): void
}

const panels = new Map<string, NiivueSegmentationPane>()

/** The NiiVue pane showing `segmentationId` in the panel, if any. */
export function niivueSegmentationPane(
  segmentationId: string | undefined,
): NiivueSegmentationPane | undefined {
  for (const pane of panels.values())
    if (pane.segmentationId === segmentationId) return pane
  return undefined
}

/**
 * The panel's "click segment" on a NiiVue pane: activate it and move the
 * crosshair to its centroid. False when the pane does not show `segmentationId`.
 */
export function jumpToNiivueSegment(
  servicesManager: OhifServicesManager | undefined,
  viewportId: string | undefined,
  segmentationId: string,
  segmentIndex: number,
): boolean {
  const panel = viewportId ? panels.get(viewportId) : undefined
  if (!viewportId || panel?.segmentationId !== segmentationId) return false
  const service = ohifServices(servicesManager)?.segmentationService
  service?.setActiveSegmentation(viewportId, segmentationId)
  service?.setActiveSegment(segmentationId, segmentIndex)
  panel.jump(segmentIndex)
  return true
}

/**
 * List `seg`'s segments (shown as `nv`'s drawing) in OHIF's segmentation panel
 * for `viewportId` and mirror panel visibility, colour, label, fill/outline
 * style, active segment, locks and deletions into the drawing; a SEG drawing
 * is editable with OHIF's labelmap tools (segEdit.ts). Returns the cleanup.
 */
export function startSegPanel(
  nv: NiiVue,
  viewportId: string,
  seg: OhifDisplaySet,
  segments: ReadonlyArray<PanelSegment>,
  managers: {
    servicesManager?: OhifServicesManager
    extensionManager?: OhifExtensionManager
  },
  /** RT ROIs overlap: the bitmap holds neither their stats nor hidden ones' voxels. */
  rt?: RtLabels,
  /** The drawing's owner records the panel's style as its own (see styleDrawing). */
  restyle: Restyle = (write) => write(),
): () => void {
  const cst = cornerstoneSegmentation(managers.extensionManager)
  const service = ohifServices(managers.servicesManager)?.segmentationService
  const bitmap = nv.drawingVolume?.img
  const back = nv.volumes[0]
  // The id is the SEG display set's, as OHIF's own: a segmentation added under
  // another id makes OHIF create a display set for it.
  const segmentationId = seg.displaySetInstanceUID
  if (
    !cst ||
    !service ||
    !(bitmap instanceof Uint8Array) ||
    !back?.dimsRAS ||
    !segmentationId
  )
    return () => {}
  const dims = back.dimsRAS.slice(1, 4)
  // A pane joining after edits shows them: the original SEG lacks them.
  const peer = niivueSegmentationPane(segmentationId)?.nv.drawingVolume?.img
  if (!rt && peer instanceof Uint8Array && peer.length === bitmap.length) {
    bitmap.set(peer)
    nv.refreshDrawing()
  }
  let stats = rt?.stats ?? labelStats(bitmap, dims)
  const grid = rasGrid(back)
  // |det| of the affine: pixDims overstate a sheared grid's voxel.
  const [, px = 1, py = 1, pz = 1] = back.hdr?.pixDims ?? []
  const voxel = grid ? voxelMM3(grid) : px * py * pz
  const cached = (value: number) =>
    segmentStats(stats.get(value)?.count ?? 0, voxel)
  // A second pane on the same SEG shares the segmentation, with its own
  // colours; segments added later take palette colours.
  const lut: Color[] = [[0, 0, 0, 0]]
  for (let i = 1; i < 256; i++) lut[i] = paletteColor(i)
  for (const s of segments) lut[s.value] = [...s.rgb, 255]
  if (!cst.state.getSegmentation(segmentationId)) {
    cst.addSegmentations([
      {
        segmentationId,
        representation: { type: LABELMAP, data: { imageIds: [] } },
        config: {
          label: seg.SeriesDescription,
          fallbackLabel: `S:${seg.SeriesNumber ?? ''} ${seg.Modality ?? 'SEG'}`,
          segments: Object.fromEntries(
            segments.map((s) => [
              s.value,
              {
                segmentIndex: s.value,
                label: s.label,
                locked: false,
                active: false,
                cachedStats: cached(s.value),
              },
            ]),
          ),
        },
      },
    ])
    // OHIF offers Save only for a labelmap it can scan in cornerstone's cache
    // (or a segmentation with no voxel representation); NiiVue keeps the
    // voxels, so the entry carries none and the save commands read the drawing.
    const added = cst.state.getSegmentation(segmentationId) as
      | { representationData?: Record<string, unknown> }
      | undefined
    if (added?.representationData) delete added.representationData[LABELMAP]
  }
  // removeColorLUT leaves a hole and addColorLUT appends by default: fill the first hole.
  let freeIndex = 0
  while (cst.state.getColorLUT(freeIndex)) freeIndex++
  const lutIndex = cst.config.color.addColorLUT(lut, freeIndex)
  addRepresentation(cst, viewportId, segmentationId, lutIndex)

  const specifier = { segmentationId, type: LABELMAP }
  const colormapName = `seg-panel-${viewportId}`
  let applied = ''
  let present = new Set(segments.map((s) => s.value))
  let locked = new Set<number>()
  // RT: the voxels shown, as filled (all ROIs) at first.
  let shown = segments.map((s) => s.value).join()
  const readRows = () => {
    const segmentation = cst.state.getSegmentation(segmentationId)
    const rep = cst.state.getSegmentationRepresentation(viewportId, specifier)
    if (!segmentation || !rep) return undefined
    return Object.entries(segmentation.segments).map(([key, s]) => {
      const value = Number(key)
      return {
        value,
        label: s.label ?? key,
        color: cst.config.color.getSegmentIndexColor(
          viewportId,
          segmentationId,
          value,
        ) ?? [0, 0, 0, 0],
        visible:
          rep.visible !== false && rep.segments?.[value]?.visible !== false,
        active: s.active === true,
        locked: s.locked === true,
      }
    })
  }
  const sync = () => {
    // A segmentation created on this pane since owns its drawing.
    if (panels.get(viewportId)?.segmentationId !== segmentationId) return
    restyle(() => {
      const rows = readRows()
      // Deleted or removed from the pane in the panel: hide the drawing.
      if (!rows) {
        applied = ''
        nv.drawOpacity = 0
        nv.drawRimOpacity = -1
        return
      }
      const now = new Set(rows.map((r) => r.value))
      // A deleted segment's voxels go, as cornerstone clears them.
      if (!rt)
        for (const v of present) if (!now.has(v)) eraseSegmentValue(nv, v)
      present = now
      locked = new Set(rows.filter((r) => r.locked).map((r) => r.value))
      // Until the panel activates one, the pen paints the first listed segment.
      const active = rows.find((r) => r.active) ?? rows[0]
      if (active && !rt) setActiveSegmentValue(nv, active.value)
      const role = segmentationRole(service, cst, viewportId, segmentationId)
      const drawn = drawOpacities(
        cst.config.style.getStyle({ viewportId, ...specifier }),
        role !== 'inactive',
      )
      const { fill, rim, width, outlineOnly } =
        role === 'hidden' ? { ...drawn, fill: 0, rim: -1 } : drawn
      // Events fire for unrelated edits too; rebuilding the drawing texture is not free.
      const visibleRows = rows.map(({ value, label, color, visible }) => ({
        value,
        label,
        // Outline only: the rim ignores colour alpha, but a faint colour would
        // round the 1/255 fill's texel alpha to 0, which hides the rim too.
        color: outlineOnly ? ([...color.slice(0, 3), 255] as Color) : color,
        visible,
      }))
      const key = JSON.stringify([visibleRows, fill, rim, width])
      if (key === applied) return
      applied = key
      const visible = rows.filter((r) => r.visible).map((r) => r.value)
      if (rt && visible.join() !== shown) {
        shown = visible.join()
        rt.showOnly(new Set(visible))
      }
      nv.drawColormap = nv.addColormap(colormapName, panelColormap(visibleRows))
      nv.drawOpacity = fill
      nv.drawRimOpacity = rim
      nv.drawRimWidth = width
    })
  }
  panels.set(viewportId, {
    viewportId,
    segmentationId,
    nv,
    seg,
    rt,
    rows: () =>
      (readRows() ?? []).map((r) => ({
        value: r.value,
        label: r.label,
        rgb: [r.color[0] ?? 0, r.color[1] ?? 0, r.color[2] ?? 0],
        ...cached(r.value),
        locked: r.locked,
        active: r.active,
        visible: r.visible,
      })),
    jump: (index) => {
      const centroid = stats.get(index)?.centroid
      const mm = centroid && nv.vox2mm(centroid)
      if (mm) nv.setCrosshairPos(mm)
    },
    // Not cornerstone's removeSegment: it needs the labelmap data this entry
    // omits so OHIF offers Save.
    deleteSegment: (index) => {
      const segment = cst.state.getSegmentation(segmentationId)?.segments[index]
      if (!segment) return
      const setSegment = (s?: Segment) => {
        const segments = cst.state.getSegmentation(segmentationId)?.segments
        if (!segments) return
        if (s) segments[index] = s
        else {
          delete segments[index]
          // Its voxels are handled here: spare sync a second erase scan.
          present.delete(index)
        }
        cst.triggerSegmentationEvents.triggerSegmentationModified(
          segmentationId,
        )
      }
      // Voxels first: the removal's sync would erase them unrecorded.
      const erased = rt ? undefined : eraseSegmentValue(nv, index)
      setSegment()
      historyMemo(managers.extensionManager)?.push({
        id: crypto.randomUUID(),
        restoreMemo: (undo) => {
          // Inert once the segmentation's panes at deletion have all stopped.
          if (erased && !erased(undo ? index : 0)) return
          // Not active: the panel may have activated another meanwhile.
          setSegment(undo ? { ...segment, active: false } : undefined)
        },
      })
    },
  })
  sync()

  // Edits refresh the panel's statistics.
  const onEdit = () => {
    const img = nv.drawingVolume?.img
    if (!(img instanceof Uint8Array)) return
    stats = labelStats(img, dims)
    const segmentation = cst.state.getSegmentation(segmentationId)
    if (!segmentation) return
    for (const [key, s] of Object.entries(segmentation.segments))
      s.cachedStats = { ...s.cachedStats, ...cached(Number(key)) }
    cst.triggerSegmentationEvents.triggerSegmentationModified(segmentationId)
  }
  // ponytail: RT drawings stay read-only (overlapping ROIs share the bitmap).
  const stopEditing = rt
    ? () => {}
    : startSegEditing(nv, {
        toolGroupId: getNiivueEntry(viewportId)?.toolGroupId,
        group: segmentationId,
        extensionManager: managers.extensionManager,
        locked: () => locked,
        onEdit,
      })

  const { EVENTS } = service
  const subscriptions = [
    EVENTS.SEGMENTATION_MODIFIED,
    EVENTS.SEGMENTATION_REPRESENTATION_MODIFIED,
    EVENTS.SEGMENTATION_STYLE_MODIFIED,
    EVENTS.SEGMENTATION_REMOVED,
    EVENTS.SEGMENTATION_REPRESENTATION_REMOVED,
  ]
    .filter((event): event is string => !!event)
    .map((event) =>
      service.subscribe(event, (e) => {
        // Activating another segmentation on the pane restyles this one.
        if (
          !e?.segmentationId ||
          e.segmentationId === segmentationId ||
          event === EVENTS.SEGMENTATION_REPRESENTATION_MODIFIED
        )
          sync()
      }),
    )
  return () => {
    for (const s of subscriptions) s.unsubscribe()
    stopEditing()
    if (panels.get(viewportId)?.segmentationId === segmentationId)
      panels.delete(viewportId)
    // The segmentation stays, as OHIF leaves its own: removing it makes OHIF
    // strip the SEG display set from every viewport that hangs it.
    cst.removeSegmentationRepresentations(viewportId, { segmentationId })
    // Each start adds one: without this, toggling a SEG grows cornerstone's LUT list.
    cst.state.removeColorLUT(lutIndex)
  }
}

export function addRepresentation(
  cst: CstSegmentation,
  viewportId: string,
  segmentationId: string,
  colorLUTIndex: number,
  type = LABELMAP,
): void {
  const manager = cst.defaultSegmentationStateManager
  manager.updateState((state) => {
    state.viewportSegRepresentations[viewportId] ??= []
    manager.addDefaultSegmentationRepresentation(
      state,
      viewportId,
      segmentationId,
      type,
      {
        colorLUTIndex,
      },
    )
  })
  // As cornerstone's own first representation on a viewport.
  cst.segmentationStyle.setRenderInactiveSegmentations(viewportId, true)
  cst.triggerSegmentationEvents.triggerSegmentationRepresentationModified(
    viewportId,
    segmentationId,
    type,
  )
}
